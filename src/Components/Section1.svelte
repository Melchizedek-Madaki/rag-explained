<h1 class="body-header">Why a smart AI can still get it wrong</h1>

<p class="body-text">
  Imagine you ask a chatbot: <em>"What's the reimbursement policy for setting
  up my home office?"</em>
</p>

<Section1Visual />

<p class="body-text">
  It sounds like an easy question. But the chatbot has never seen your
  company's policy documents. They're private, so they were never part of what
  it learned from.
</p>

<p class="body-text">
  So what does it do? It doesn't say "I don't know." It writes an answer that
  <em>sounds</em> right, based on what's typical at most companies. That's
  called a <span class="bold">hallucination</span>: a confident answer that
  may be wrong.
</p>

<p class="body-text">
  The AI isn't dumb. It's just missing the right information at the moment you
  ask.
</p>

<p class="body-text">
  So what if we handed the AI the right page <em>before</em> it answered?
</p>